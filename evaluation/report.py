"""Markdown reports from saved eval results.

    python -m evaluation.report tickets [results.json]   # per-ticket pass/fail table -> docs/EVAL_REPORT.md
    python -m evaluation.report compare --prompt v5      # model comparison table (stdout)

A ticket PASSES when everything the task asks for is right: primary category,
priority, needs_human, every required risk flag, and no false risk flag.
"""

import argparse
import json
import statistics
from pathlib import Path
from typing import Optional

from classifier.config import RESULTS_DIR, ROOT
from evaluation.scoring import FIELDS

PASS_FIELDS = ("category", "priority", "needs_human", "flags_required")

# USD per 1M tokens (input, output). Local models have no API price.
PRICES = {
    "claude-haiku-5-5": (0.10, 0.50),
    "claude-sonnet-5-5": (2.00, 10.00),
    "claude-opus-5-5": (4.00, 20.00),
}


def passed(row: dict) -> bool:
    return all(row["scores"][f] is not False for f in PASS_FIELDS) and not row["false_flags"]


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def latest_per_model(prompt: str) -> list[dict]:
    """Most recent full-test-set run for every provider/model on this prompt."""
    runs: dict[str, tuple[str, dict]] = {}
    for p in sorted(RESULTS_DIR.glob(f"{prompt}_*.json")):
        rep = load(p)
        if rep["run"]["n_tickets"] < 40:
            continue
        key = f"{rep['run']['provider']}/{rep['run']['model']}"
        runs[key] = (p.name, rep)  # sorted by timestamp, so the last one wins
    return [rep | {"file": name} for name, rep in runs.values()]


def _cell(text: str, n: int = 70) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    return text if len(text) <= n else text[: n - 1] + "…"


def _actual(row: dict) -> str:
    ext, d = row["result"]["extraction"], row["result"]["routing"]
    intents = " + ".join(i["sub_intent"] for i in ext["intents"]) if ext else "FAILED"
    flags = f" ⚑{','.join(row['result']['risk_flags'])}" if row["result"]["risk_flags"] else ""
    return f"{intents} · {d['priority']} · {'human' if d['needs_human'] else 'auto'}{flags}"


def _expected(row: dict) -> str:
    e = row["expected"]
    sub = " \\| ".join(e["primary_sub_intent"]) or "(any)"
    flags = f" ⚑{','.join(e['risk_flags'])}" if e["risk_flags"] else ""
    return f"{sub} · {e['priority']} · {'human' if e['needs_human'] else 'auto'}{flags}"


def tickets_report(rep: dict, source: str) -> str:
    r, rows = rep["run"], rep["rows"]
    n_pass = sum(passed(x) for x in rows)
    out = [
        "# Evaluation report",
        "",
        f"Generated by `python -m evaluation.report tickets` from `{source}`.",
        "",
        f"**Run:** {r['provider']}/{r['model']} · prompt {r['prompt_version']} · {r['n_tickets']} tickets · {r['timestamp']}",
        "",
        f"**Overall accuracy (ticket passes all of: category, priority, needs_human, required flags, no false flags): "
        f"{n_pass}/{len(rows)} = {n_pass / len(rows):.0%}**",
        "",
        "| Field | Correct | Accuracy |",
        "|---|---|---|",
    ]
    for f in FIELDS:
        t = rep["summary"]["fields"][f]
        if t["total"]:
            out.append(f"| {f} | {t['correct']}/{t['total']} | {t['accuracy']:.0%} |")
    out += [
        "",
        "Expected/actual format: `sub-intent · priority · human|auto ⚑flags`. "
        "Several expected sub-intents separated by `|` are all acceptable.",
        "",
        "| ID | Input | Expected | Actual | Result |",
        "|---|---|---|---|---|",
    ]
    for x in rows:
        out.append(f"| {x['id']} | {_cell(x['text'])} | {_expected(x)} | {_actual(x)} | {'✅ pass' if passed(x) else '❌ fail'} |")

    fails = [x for x in rows if not passed(x)]
    out += ["", "## Failures", ""]
    if not fails:
        out.append("None.")
    for x in fails:
        misses = [f for f in PASS_FIELDS if x["scores"][f] is False] + [f"false flag: {f}" for f in x["false_flags"]]
        ext = x["result"]["extraction"]
        out += [f"**{x['id']}**: {', '.join(misses)}  ",
                f"Rule: `{x['result']['routing']['rule_id']}`, modifiers: {x['result']['routing']['modifiers'] or '-'}  ",
                f"Model reasoning: _{ext['reasoning'] if ext else x['error']}_", ""]
    return "\n".join(out) + "\n"


def cost_per_ticket(model: str, tokens_in: Optional[float], tokens_out: Optional[float]) -> Optional[float]:
    if model not in PRICES or tokens_in is None or tokens_out is None:
        return None
    p_in, p_out = PRICES[model]
    return (tokens_in * p_in + tokens_out * p_out) / 1e6


def compare_table(prompt: str) -> str:
    out = [
        "| Model | Overall pass | Category | Sub-intent | Priority | needs_human | Req. flags | False flags | Failures "
        "| Latency avg / p95 | Tokens in / out | API $ / ticket |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for rep in sorted(latest_per_model(prompt), key=lambda r: -sum(passed(x) for x in r["rows"])):
        rows, s = rep["rows"], rep["summary"]
        f = s["fields"]
        lat = sorted(x["latency_ms"] for x in rows if x.get("latency_ms"))
        p95 = lat[min(len(lat) - 1, int(0.95 * len(lat)))] if lat else None
        cost = cost_per_ticket(rep["run"]["model"], s["avg_input_tokens"], s["avg_output_tokens"])
        pct = lambda k: f"{f[k]['accuracy']:.0%}" if f[k]["total"] else "-"
        out.append(
            f"| {rep['run']['provider']}/{rep['run']['model']} | {sum(passed(x) for x in rows)}/{len(rows)} "
            f"| {pct('category')} | {pct('sub_intent')} | {pct('priority')} | {pct('needs_human')} "
            f"| {f['flags_required']['correct']}/{f['flags_required']['total']} | {sum(s['false_flags'].values())} "
            f"| {s['extraction_failures']} | {statistics.mean(lat) / 1000:.1f}s / {p95 / 1000:.1f}s "
            f"| {s['avg_input_tokens']} / {s['avg_output_tokens']} | {f'${cost:.5f}' if cost is not None else 'local'} |"
        )
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("tickets")
    t.add_argument("results", nargs="?", help="results JSON (default: latest full run of --prompt on --model)")
    t.add_argument("--prompt", default="v5")
    t.add_argument("--model", default="llama3.1")
    t.add_argument("--out", default=str(ROOT / "docs" / "EVAL_REPORT.md"))
    c = sub.add_parser("compare")
    c.add_argument("--prompt", default="v5")
    args = parser.parse_args()

    if args.cmd == "tickets":
        if args.results:
            path = Path(args.results)
        else:
            reps = [r for r in latest_per_model(args.prompt) if r["run"]["model"] == args.model]
            path = RESULTS_DIR / reps[0]["file"]
        Path(args.out).write_text(tickets_report(load(path), path.name), encoding="utf-8")
        print(f"Wrote {args.out}")
    else:
        print(compare_table(args.prompt))


if __name__ == "__main__":
    main()
