"""Offline LLM judge for reply-assistant drafts (never used at runtime).

Rates every draft of a saved eval run with the rubric from the agentic-RAG
copilot paper (appropriate / too general / inappropriate), plus groundedness,
tone fit and translation fidelity.

    python -m evaluation.judge evaluation/results/assistant/v3_ollama_llama3.1_....json --judge-model gemma3:12b
    python -m evaluation.judge <results.json> --report     # also writes docs/ASSISTANT_JUDGE_REPORT.md

Caveat: an LLM judge is a proxy for human review. When the judge model also
wrote the drafts, expect self-preference bias.
"""

import argparse
import json
from collections import Counter
from enum import Enum
from pathlib import Path

from pydantic import BaseModel, Field

from assistant.generator import language_name
from classifier.config import PROMPTS_DIR, RESULTS_DIR, ROOT
from classifier.llm import get_client
from classifier.llm.base import LLMClient, LLMError
from classifier.prompts import load_prompt

JUDGE_PROMPTS_DIR = PROMPTS_DIR / "judge"
OUT_DIR = RESULTS_DIR / "assistant" / "judged"
TONES = ("formal", "empathetic", "short")


class Rating(str, Enum):
    APPROPRIATE = "appropriate"
    TOO_GENERAL = "too_general"
    INAPPROPRIATE = "inappropriate"


class DraftVerdict(BaseModel):
    tone: str
    rating: Rating
    grounded: bool
    unsupported_claims: list[str] = Field(description="Factual claims not supported by the KB or the ticket.")
    tone_ok: bool
    translation_ok: bool
    issue: str


class TicketVerdict(BaseModel):
    verdicts: list[DraftVerdict] = Field(description="Exactly three verdicts: formal, empathetic, short.")


def build_message(row: dict) -> str:
    res = row["result"]
    ext = res["triage"]["extraction"]
    lang = ext["language"] if ext else "en"
    kb = "\n".join(f'<article id="{s["id"]}" audience="{s["audience"]}"'
                   + (f' condition="{s["condition"]}"' if s.get("condition") else "")
                   + f'>\n{s["title"]}\n{s["body"]}\n</article>' for s in res["sources"]) or "(none)"
    drafts = []
    for d in res["drafts"]["drafts"]:
        block = f'<draft tone="{d["tone"]}">\n<english>\n{d["english"]}\n</english>'
        if lang != "en":
            block += f'\n<local language="{language_name(lang)}">\n{d["local"]}\n</local>'
        drafts.append(block + "\n</draft>")
    return (f'<ticket language="{lang}">\n{row["text"]}\n</ticket>\n\n'
            f'Billing channel known to the system: {res["meta"]["channel"]}\n\n'
            f"<kb>\n{kb}\n</kb>\n\n" + "\n\n".join(drafts))


def judge_run(results_path: Path, client: LLMClient, prompt_version: str = "latest", progress=None) -> dict:
    report = json.loads(results_path.read_text(encoding="utf-8"))
    version, system_prompt = load_prompt(prompt_version, JUDGE_PROMPTS_DIR)
    rows = [r for r in report["rows"] if r["result"]["drafts"]]
    judged = []
    for n, row in enumerate(rows, 1):
        entry = {"id": row["id"], "text": row["text"], "verdicts": None, "error": None}
        try:
            resp = client.generate_structured(system_prompt, build_message(row), TicketVerdict)
            entry["verdicts"] = [v.model_dump(mode="json") for v in resp.parsed.verdicts]
        except LLMError as e:
            entry["error"] = str(e)
        judged.append(entry)
        if progress:
            progress(n, len(rows), entry)

    verdicts = [v for j in judged if j["verdicts"] for v in j["verdicts"]]
    by_tone = {t: Counter(v["rating"] for v in verdicts if v["tone"] == t) for t in TONES}
    summary = {
        "drafts_judged": len(verdicts),
        "ratings": dict(Counter(v["rating"] for v in verdicts)),
        "ratings_by_tone": {t: dict(c) for t, c in by_tone.items()},
        "grounded": sum(v["grounded"] for v in verdicts),
        "tone_ok": sum(v["tone_ok"] for v in verdicts),
        "translation_ok": sum(v["translation_ok"] for v in verdicts),
        "judge_failures": sum(1 for j in judged if j["error"]),
    }
    return {"source": results_path.name, "generator": report["run"], "judge_model": f"{client.provider}/{client.model}",
            "judge_prompt": version, "summary": summary, "tickets": judged}


def latest_judged() -> list[dict]:
    """Most recent judged file per (generator model, judge model)."""
    latest: dict[tuple, dict] = {}
    for f in sorted(OUT_DIR.glob("*.json")):
        j = json.loads(f.read_text(encoding="utf-8"))
        latest[(j["generator"]["model"], j["judge_model"])] = j
    return list(latest.values())


def report_all(judged: list[dict]) -> str:
    out = ["# Reply assistant: LLM-judge report", "",
           "Generated by `python -m evaluation.judge --report` from every judged run in `evaluation/results/assistant/judged/`. "
           "An LLM judge is a proxy for human review; treat it as a second opinion, not ground truth. "
           "When the judge model also wrote the drafts, expect self-preference bias.", "",
           "| Drafts by | Judged by | Appropriate | Too general | Inappropriate | Grounded | Tone fits | Translation faithful |",
           "|---|---|---|---|---|---|---|---|"]
    for j in judged:
        s = j["summary"]
        n = s["drafts_judged"]
        r = lambda k: f"{s['ratings'].get(k, 0)}/{n}"
        out.append(f"| {j['generator']['model']} (prompt {j['generator']['prompt_version']}) | {j['judge_model']} "
                   f"| {r('appropriate')} | {r('too_general')} | {r('inappropriate')} | {s['grounded']}/{n} "
                   f"| {s['tone_ok']}/{n} | {s['translation_ok']}/{n} |")
    return "\n".join(out) + "\n\n" + "\n".join(markdown(j) for j in judged)


def markdown(j: dict) -> str:
    s, g = j["summary"], j["generator"]
    n = s["drafts_judged"] or 1
    pct = lambda k: f"{s['ratings'].get(k, 0)}/{s['drafts_judged']} ({s['ratings'].get(k, 0) / n:.0%})"
    out = [f"## Drafts by {g['provider']}/{g['model']}, judged by {j['judge_model']}", "",
           f"Source `{j['source']}`, drafts prompt {g['prompt_version']}, judge prompt {j['judge_prompt']}.", "",
           "| Metric | Result |", "|---|---|",
           f"| Appropriate | {pct('appropriate')} |", f"| Too general | {pct('too_general')} |",
           f"| Inappropriate | {pct('inappropriate')} |",
           f"| Grounded in KB | {s['grounded']}/{s['drafts_judged']} |", f"| Tone fits | {s['tone_ok']}/{s['drafts_judged']} |",
           f"| Translation faithful | {s['translation_ok']}/{s['drafts_judged']} |", f"| Judge failures | {s['judge_failures']} |", "",
           "| Tone | Appropriate | Too general | Inappropriate |", "|---|---|---|---|"]
    for t in TONES:
        c = s["ratings_by_tone"][t]
        out.append(f"| {t} | {c.get('appropriate', 0)} | {c.get('too_general', 0)} | {c.get('inappropriate', 0)} |")
    out += ["", "**Drafts not rated appropriate, or with unsupported claims:**", ""]
    for t in j["tickets"]:
        for v in t["verdicts"] or []:
            if v["rating"] != "appropriate" or v["unsupported_claims"]:
                claims = f" Unsupported: {'; '.join(v['unsupported_claims'])}." if v["unsupported_claims"] else ""
                out.append(f"- **{t['id']} / {v['tone']}**: {v['rating']}. {v['issue']}{claims}")
    return "\n".join(out) + "\n"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("results")
    p.add_argument("--judge-provider", default="ollama")
    p.add_argument("--judge-model", default="gemma3:12b")
    p.add_argument("--prompt", default="latest")
    p.add_argument("--report", action="store_true")
    a = p.parse_args()

    client = get_client(a.judge_provider, a.judge_model)
    j = judge_run(Path(a.results), client, a.prompt,
                  lambda n, total, e: print(f"[{n:>2}/{total}] {e['id']} "
                                            + (e["error"][:80] if e["error"] else " ".join(v["rating"][:5] for v in e["verdicts"])), flush=True))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"{Path(a.results).stem}__judge_{a.judge_model.replace(':', '_')}.json"
    out.write_text(json.dumps(j, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(j["summary"], indent=2))
    print(f"Saved: {out}")
    if a.report:
        doc = ROOT / "docs" / "ASSISTANT_JUDGE_REPORT.md"
        doc.write_text(report_all(latest_judged()), encoding="utf-8")
        print(f"Wrote {doc}")


if __name__ == "__main__":
    main()
